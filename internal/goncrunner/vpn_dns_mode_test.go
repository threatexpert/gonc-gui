package goncrunner

import (
	"os"
	"path/filepath"
	"runtime"
	"testing"
)

func TestResolvConfSymlinkUsesStub(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("Linux resolv.conf symlinks")
	}
	dir := t.TempDir()
	upstream := filepath.Join(dir, "resolv.conf")
	stub := filepath.Join(dir, "stub-resolv.conf")
	for _, tt := range []struct {
		path string
		want bool
	}{{upstream, false}, {stub, true}} {
		t.Run(filepath.Base(tt.path), func(t *testing.T) {
			// Even if both files currently list the stub, the upstream list
			// can change as interfaces come and go during the VPN session.
			if err := os.WriteFile(tt.path, []byte("nameserver 127.0.0.53\n"), 0600); err != nil {
				t.Fatal(err)
			}
			conf := filepath.Join(t.TempDir(), "resolv.conf")
			if err := os.Symlink(tt.path, conf); err != nil {
				t.Fatal(err)
			}
			if got := resolvConfUsesStub(conf, upstream); got != tt.want {
				t.Errorf("resolvConfUsesStub() = %t, want %t", got, tt.want)
			}
		})
	}
}

func TestUsesResolvedStub(t *testing.T) {
	for _, tt := range []struct {
		name string
		conf string
		want bool
	}{
		{"stub", "search example.test\n nameserver\t127.0.0.53 # local stub", true},
		{"proxy stub", "nameserver 127.0.0.54", true},
		{"NetworkManager upstream", "# Generated by NetworkManager\nnameserver 192.168.55.2", false},
		{"mixed", "nameserver 127.0.0.53\nnameserver 192.168.55.2", false},
		{"comment only", "; nameserver 127.0.0.53", false},
		{"malformed", "nameserver", false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if got := usesResolvedStub(tt.conf); got != tt.want {
				t.Errorf("usesResolvedStub() = %v, want %v", got, tt.want)
			}
		})
	}
}
